// Isolated renderer smoke: uses canned messages and never calls a model API.
const { app, BrowserWindow, ipcMain } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'bubble-verification');
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(output, 'electron-profile'));
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
let win;
const sent = [];
const results = {};
app.whenReady().then(async () => {
  const { rendererSource, readArt } = await import(pathToFileURL(path.join(root, 'hagemi-pet/sidecars/pet/lib/renderer-source.mjs')));
  const { UI } = await import(pathToFileURL(path.join(root, 'hagemi-pet/sidecars/pet/lib/lines.mjs')));
  const { DEFAULTS } = await import(pathToFileURL(path.join(root, 'hagemi-pet/sidecars/pet/lib/settings.mjs')));
  win = new BrowserWindow({ width: 940, height: 760, show: false, frame: false, transparent: true,
    webPreferences: { preload: path.join(root, 'hagemi-pet/desktop/preload.cjs'), contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false, offscreen: true } });
  const post = msg => win.webContents.send('hagemi:to-pet', msg);
  ipcMain.on('hagemi:from-pet', (_event, raw) => {
    const msg = JSON.parse(raw);
    sent.push(msg);
    if (msg.type === 'art') post({ t: 'art', name: msg.name, data: readArt(msg.name) });
  });
  await win.loadFile(path.join(root, 'hagemi-pet/desktop/index.html'));
  let { source } = rendererSource({ standalone: true, desktop: true });
  source = source.replace("const root = host.attachShadow({ mode: 'closed' });", "const root = host.attachShadow({ mode: 'closed' }); window.__testRoot = root;");
  await win.webContents.executeJavaScript(source);
  await win.webContents.executeJavaScript('window.__hagemiFlushQueue()');
  post({ t: 'hello', ui: UI.zhs, settings: { ...DEFAULTS, language: 'zhs', muted: true, position: { x: .66, y: .74 }, ai: { ...DEFAULTS.ai, enabled: false } } });
  const evaluate = js => win.webContents.executeJavaScript(js);
  await delay(1200);
  assert.ok(!sent.some(m => m.type === 'error'), JSON.stringify(sent.filter(m => m.type === 'error')));
  // Second click at 320 ms exercises the whole advertised double-click interval.
  await evaluate("window.__testRoot.querySelector('.hit').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:620,clientY:560}))");
  await delay(320);
  await evaluate("window.__testRoot.querySelector('.hit').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:620,clientY:560}))");
  await delay(100);
  results.compactInput = await evaluate("({open:window.__testRoot.querySelector('.chat-box').classList.contains('show'),history:!!window.__testRoot.querySelector('.chat-log'),height:window.__testRoot.querySelector('.chat-box').offsetHeight})");
  assert.equal(results.compactInput.open, true);
  assert.equal(results.compactInput.history, false);
  assert.ok(results.compactInput.height < 180);
  await evaluate("window.__testRoot.querySelector('.chat-input').value='你能用头顶气泡回答我吗？'");
  await delay(100);
  fs.writeFileSync(path.join(output, 'input.png'), (await win.webContents.capturePage()).toPNG());
  await evaluate("window.__testRoot.querySelector('.chat-input').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))");
  await delay(80);
  results.submit = await evaluate("({inputHidden:!window.__testRoot.querySelector('.chat-box').classList.contains('show'),bubble:window.__testRoot.querySelector('.bubble').classList.contains('show'),text:window.__testRoot.querySelector('.bubble .text').textContent})");
  assert.equal(results.submit.inputHidden, true);
  assert.equal(results.submit.bubble, true);
  assert.ok(sent.some(m => m.type === 'chat_send'));
  assert.equal(sent.filter(m => m.type === 'desktop_focus').at(-1).focused, false);
  const reply = '当然可以喵～你输入后，输入条会自动收起，我会在头顶的小气泡里逐字回答你。长一点的回复也可以滚动查看、选中复制。';
  post({ t: 'chat_start', requestId: 1 });
  post({ t: 'chat_done', requestId: 1, text: reply });
  await delay(280);
  const partial = await evaluate("window.__testRoot.querySelector('.bubble .text').textContent");
  assert.ok(partial.length > 0 && partial.length < reply.length, `typewriter partial: ${JSON.stringify(partial)}`);
  await delay(2000);
  assert.equal(await evaluate("window.__testRoot.querySelector('.bubble .text').textContent"), reply);
  results.hostTypewriter = true;
  results.explicitReplyWhileMuted = true;
  fs.writeFileSync(path.join(output, 'bubble.png'), (await win.webContents.capturePage()).toPNG());
  fs.writeFileSync(path.join(output, 'bubble-preview.png'), (await win.webContents.capturePage({x:430,y:330,width:390,height:370})).toPNG());
  post({ t: 'chat_start', requestId: 2 });
  post({ t: 'chat_delta', requestId: 2, fullText: '流式回答第一段' });
  await delay(70);
  assert.equal(await evaluate("window.__testRoot.querySelector('.bubble .text').textContent"), '流式回答第一段');
  post({ t: 'say', text: '不应打断的环境吐槽' });
  await delay(100);
  assert.equal(await evaluate("window.__testRoot.querySelector('.bubble .text').textContent"), '流式回答第一段');
  const longReply = Array.from({ length: 24 }, (_, i) => `${i + 1}. 这是长回答的滚动阅读测试，气泡保留小尾巴。`).join('\n');
  post({ t: 'chat_delta', requestId: 2, fullText: longReply });
  post({ t: 'chat_done', requestId: 2, text: longReply });
  await delay(200);
  results.longBubble = await evaluate(`(() => {
    const b=window.__testRoot.querySelector('.bubble'),t=b.querySelector('.text');
    return {width:b.offsetWidth,height:b.offsetHeight,scrollable:t.scrollHeight>t.clientHeight,tailVisible:getComputedStyle(b).overflow==='visible',autoScroll:t.scrollTop>0};
  })()`);
  assert.ok(results.longBubble.width <= 320 && results.longBubble.height <= 232);
  assert.ok(results.longBubble.scrollable && results.longBubble.tailVisible && results.longBubble.autoScroll);
  results.selection = await evaluate(`(() => {
    const b=window.__testRoot.querySelector('.bubble'),t=b.querySelector('.text');
    const selection=window.getSelection(),range=document.createRange();range.selectNodeContents(t);selection.removeAllRanges();selection.addRange(range);
    const selected=selection.toString();b.dispatchEvent(new MouseEvent('click',{bubbles:true}));
    const staysOpen=b.classList.contains('show');selection.removeAllRanges();return {selected:selected.length>0,staysOpen};
  })()`);
  assert.ok(results.selection.selected && results.selection.staysOpen);
  fs.writeFileSync(path.join(output, 'long-bubble.png'), (await win.webContents.capturePage()).toPNG());
  results.sse = true;
  results.modelGenerationRequested = false;
  fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results));
  win.destroy();app.quit();
}).catch(error => { console.error(error); if (win && !win.isDestroyed()) win.destroy(); app.exit(1); });
